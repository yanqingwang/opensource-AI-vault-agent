var VaultToolExecutor = class {
  constructor(app, getActivePath) {
    this.app = app;
    this.getActivePath = getActivePath;
  }
  async execute(name, argsJson) {
    let parsed = {};
    try {
      parsed = JSON.parse(argsJson || "{}");
    } catch {
      return { ok: false, content: "invalid JSON arguments" };
    }
    const args = parsed !== null && typeof parsed === "object" ? parsed : {};
    const s = (key, fallback = "") => {
      const v = args[key];
      switch (typeof v) {
        case "string":
          return v;
        case "number":
        case "bigint":
        case "boolean":
          return String(v);
        case "object":
          return v !== null ? JSON.stringify(v) : fallback;
        default:
          return fallback;
      }
    };
    const b = (key) => args[key] === true;
    try {
      switch (name) {
        case "list_notes":
          return ok(await this.listNotes(s("folder", "."), args.glob === void 0 ? void 0 : s("glob")));
        case "read_note":
          return ok(await this.readNote(s("path")));
        case "search_notes":
          return ok(await this.searchNotes(s("pattern"), b("regex"), args.folder === void 0 ? void 0 : s("folder")));
        case "get_active_note":
          return ok(await this.activeNote());
        case "create_note":
          return ok(await this.createNote(s("path"), s("content"), b("overwrite")));
        case "edit_note":
          return ok(await this.editNote(s("path"), s("old_string"), s("new_string"), b("replace_all")));
        case "append_note":
          return ok(await this.appendNote(s("path"), s("content")));
        case "read_properties":
          return ok(await this.readProperties(s("path")));
        default:
          return { ok: false, content: `unknown tool: ${name}` };
      }
    } catch (e) {
      return { ok: false, content: "error: " + (e instanceof Error ? e.message : String(e)) };
    }
  }
  resolve(path) {
    return (0, import_obsidian2.normalizePath)(String(path ?? "").trim().replace(/^\/+/, ""));
  }
  async listNotes(folder, glob) {
    const fp = this.resolve(folder);
    const af = this.app.vault.getAbstractFileByPath(fp);
    let files;
    if (af instanceof import_obsidian2.TFolder) {
      files = this.app.vault.getMarkdownFiles().filter((f) => f.path === fp || f.path.startsWith(fp === "/" ? "" : fp + "/"));
    } else if (af instanceof import_obsidian2.TFile) {
      files = [af];
    } else {
      files = this.app.vault.getMarkdownFiles();
    }
    if (glob)
      files = files.filter((f) => f.name.toLowerCase().includes(String(glob).toLowerCase()));
    files = files.slice(0, 500);
    if (!files.length)
      return "(no notes found)";
    return files.map((f) => `${f.path} (${f.stat.size}B)`).join("\n");
  }
  async readNote(path) {
    const file = this.mustFile(path);
    const text = await this.app.vault.cachedRead(file);
    if (text.length > MAX_READ) {
      return truncate(text, MAX_READ) + `
[note truncated; ${text.length} chars total \u2014 use search_notes or ask for a section]`;
    }
    return text || "(empty note)";
  }
  async searchNotes(pattern, regex, folder) {
    if (!pattern)
      return "empty pattern";
    let re;
    try {
      re = regex ? new RegExp(pattern, "gi") : new RegExp(pattern.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi");
    } catch (e) {
      return "invalid regex: " + (e instanceof Error ? e.message : String(e));
    }
    const fp = folder ? this.resolve(folder) : null;
    const files = this.app.vault.getMarkdownFiles().filter((f) => !fp || f.path === fp || f.path.startsWith(fp + "/"));
    const out = [];
    let hits = 0;
    for (const file of files) {
      if (hits >= MAX_RESULTS)
        break;
      const text = await this.app.vault.cachedRead(file);
      const lines = text.split("\n");
      for (let i = 0; i < lines.length && hits < MAX_RESULTS; i++) {
        re.lastIndex = 0;
        if (re.test(lines[i])) {
          out.push(`${file.path}:${i + 1}: ${lines[i].trim().slice(0, 200)}`);
          hits++;
        }
      }
    }
    return out.length ? out.join("\n") : "(no matches)";
  }
  async activeNote() {
    const path = this.getActivePath();
    if (!path)
      return "(no active note)";
    const file = this.app.vault.getFileByPath(path);
    if (!file)
      return `(active file not readable: ${path})`;
    const text = await this.app.vault.cachedRead(file);
    return `path: ${file.path}
---
` + truncate(text, MAX_READ);
  }
  /**
   * Create every missing parent folder of `path`, outermost first.
   *
   * The recursive call must pass the folder itself: passing a fake child
   * (`dir + '/x'`) recomputed the same `dir` on every level and recursed until
   * the stack overflowed, so no note could be created in a new subfolder.
   */
  async ensureFolder(path) {
    const idx = path.lastIndexOf("/");
    if (idx <= 0)
      return;
    const dir = this.resolve(path.slice(0, idx));
    if (!dir || this.app.vault.getAbstractFileByPath(dir))
      return;
    await this.ensureFolder(dir);
    if (!this.app.vault.getAbstractFileByPath(dir))
      await this.app.vault.createFolder(dir);
  }
  async createNote(path, content, overwrite) {
    const p = this.resolve(path);
    if (!p)
      return "missing path";
    if (!/\.(md|canvas)$/i.test(p))
      return "path must end with .md";
    const existing = this.app.vault.getFileByPath(p);
    if (existing) {
      if (!overwrite)
        return `file already exists: ${p}. Set overwrite=true to replace it, or use edit_note/append_note.`;
      await this.app.vault.modify(existing, content);
      return `overwrote ${p} (${content.length} chars)`;
    }
    await this.ensureFolder(p);
    await this.app.vault.create(p, content);
    return `created ${p} (${content.length} chars)`;
  }
  async editNote(path, oldString, newString, replaceAll) {
    const file = this.mustFile(path);
    const text = await this.app.vault.read(file);
    const count = text.split(oldString).length - 1;
    if (count === 0) {
      return `old_string not found in ${file.path}. Read the note again and copy the exact text (including whitespace).`;
    }
    if (count > 1 && !replaceAll) {
      return `old_string appears ${count} times in ${file.path}. Provide more surrounding lines to make it unique, or set replace_all=true.`;
    }
    const updated = replaceAll ? text.split(oldString).join(newString) : text.replace(oldString, newString);
    await this.app.vault.modify(file, updated);
    return `edited ${file.path} (${count} occurrence${count > 1 ? "s" : ""} replaced)`;
  }
  async appendNote(path, content) {
    const file = this.mustFile(path);
    const text = await this.app.vault.read(file);
    const glue = text.length && !text.endsWith("\n") ? "\n" : "";
    await this.app.vault.modify(file, text + glue + "\n" + content);
    return `appended ${content.length} chars to ${file.path}`;
  }
  async readProperties(path) {
    const file = this.mustFile(path);
    const cache = this.app.metadataCache.getFileCache(file);
    const fm = cache?.frontmatter ?? {};
    const lines = [
      `path: ${file.path}`,
      `size: ${file.stat.size}B`,
      `tags: ${(cache?.tags ?? []).map((t2) => t2.tag).join(", ") || "(none)"}`,
      `frontmatter: ${JSON.stringify(fm)}`
    ];
    return lines.join("\n");
  }
  mustFile(path) {
    const p = this.resolve(path);
    const file = this.app.vault.getFileByPath(p);
    if (!file)
      throw new Error(`note not found: ${p}`);
    if (!(file instanceof import_obsidian2.TFile))
      throw new Error(`not a file: ${p}`);
    return file;
  }
};
