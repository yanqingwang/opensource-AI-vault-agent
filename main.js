function newProfileId() {
  return "agent-" + newSessionId();
}
function makeProfile(name, presetId) {
  const preset = presetId ? PROVIDERS.find((p) => p.id === presetId) : void 0;
  const profile = { id: newProfileId(), name, ...PROFILE_DEFAULTS };
  if (preset)
    applyProviderPreset(profile, preset.id);
  return profile;
}
function applyProviderPreset(profile, providerId) {
  const preset = PROVIDERS.find((p) => p.id === providerId);
  if (!preset)
    return;
  profile.providerId = preset.id;
  profile.protocol = preset.protocol ?? "openai";
  profile.baseUrl = preset.baseUrl;
  if (preset.catalog) {
    if (!profile.model.includes("/"))
      profile.model = "";
  } else if (preset.models.length)
    profile.model = preset.models[0];
  if (preset.defaultApiKey)
    profile.apiKey = preset.defaultApiKey;
  else if (profile.apiKey === MAGPIE_KEY)
    profile.apiKey = "";
}
function migrateStarterAgent(profiles) {
  let changed = false;
  for (const profile of profiles) {
    if (profile.name !== "\u9ED8\u8BA4 Agent" && profile.name !== "Default agent")
      continue;
    const pristine = profile.providerId === PROFILE_DEFAULTS.providerId && profile.baseUrl === PROFILE_DEFAULTS.baseUrl && profile.model === PROFILE_DEFAULTS.model && !profile.apiKey.trim();
    if (!pristine)
      continue;
    const { id } = profile;
    Object.assign(profile, PROFILE_DEFAULTS, { id, name: "deepseek" });
    changed = true;
  }
  return changed;
}
function reconcileProviderIds(profiles) {
  const norm = (url) => (url || "").trim().replace(/\/+$/, "");
  let changed = false;
  for (const profile of profiles) {
    const claimed = PROVIDERS.find((p) => p.id === profile.providerId);
    if (!claimed?.baseUrl || norm(claimed.baseUrl) === norm(profile.baseUrl))
      continue;
    const match = PROVIDERS.find((p) => p.baseUrl && norm(p.baseUrl) === norm(profile.baseUrl));
    if (!match)
      continue;
    profile.providerId = match.id;
    changed = true;
  }
  return changed;
}
